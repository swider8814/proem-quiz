const dicts: Record<PanelLang, PanelDict> = { pl, en };

/** Słownik panelu dla języka (nieznany → polski). */
export const panelDict = (lang: unknown): PanelDict => dicts[isPanelLang(lang) ? lang : 'pl'];

/** Tłumaczy klucz błędu z serwera; nieznany tekst zwraca bez zmian. */
export function errText(lang: unknown, keyOrText: string): string {
	const e = panelDict(lang).err as Record<string, unknown>;
	const v = e[keyOrText];
	return typeof v === 'string' ? v : keyOrText;
}

/** Język panelu na podstawie nagłówka Accept-Language (angielski dla wszystkich poza polskim). */
export function langFromAcceptLanguage(header: string | null): PanelLang {
	if (!header) return 'pl';
	for (const part of header.split(',')) {
		const tag = part.split(';')[0].trim().toLowerCase();
		if (!tag || tag === '*') continue;
		return tag.startsWith('pl') ? 'pl' : 'en';
	}
	return 'pl';
}
